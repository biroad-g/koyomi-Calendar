  static String? getSekkiForDate(DateTime date) {
    for (int i = 0; i < _approxDates.length; i++) {
      if (_approxDates[i][0] == date.month && _approxDates[i][1] == date.day) {
        return names[i];
      }
    }
    return null;
  }
