class LunarDate {
  final int year;
  final int month;
  final int day;
  final bool isLeap;

  const LunarDate(this.year, this.month, this.day, {this.isLeap = false});

  @override
  String toString() => '$year年${isLeap ? '閏' : ''}$month月$day日';
}

